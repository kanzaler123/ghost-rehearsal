import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';
import type { Messages } from '../../src/i18n/messages';
import { MESSAGES } from '../../src/i18n/messages';
import type { ProjectDocument } from '../../src/schemas';

async function fullProject(page: Page, t: Messages) {
  await page.locator('.workspace-menu > summary').click();
  await page.getByRole('button', { name: t.header.export, exact: true }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('dialog').getByRole('button').filter({ has: page.getByText(t.dialogs.exportProject, { exact: true }) }).click();
  return readFile((await (await pending).path())!, 'utf8');
}

test('guide exports only its reproducible A/B/C experiment and preserves existing events', async ({ page }, info) => {
  const t = MESSAGES[info.project.name.endsWith('zh') ? 'zh' : 'en'];
  if (info.project.name.startsWith('mobile')) await page.setViewportSize({ width: 320, height: 720 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(lang => localStorage.setItem('ghost-rehearsal.lang', lang), t.lang);
  await page.goto('./');
  await page.getByRole('dialog').getByRole('button', { name: t.common.closeDialog, exact: true }).click();
  const original = JSON.parse(await fullProject(page, t)) as ProjectDocument;
  await page.getByRole('button', { name: t.guide.start, exact: true }).click();
  const guide = page.getByRole('region', { name: t.guide.title, exact: true });
  for (const step of [0, 1, 2, 3, 4]) await guide.getByRole('button', { name: t.guide.actions[step], exact: true }).click();
  const pickerButton = page.getByRole('button', { name: t.comparePicker.title, exact: true });
  await pickerButton.click();
  const picker = page.getByRole('dialog', { name: t.comparePicker.title, exact: true });
  await expect(picker.getByText(t.comparePicker.leaveGuide, { exact: true })).toBeVisible();
  await expect(picker.getByLabel(t.comparePicker.left, { exact: true }).locator('option')).toHaveCount(3);
  await picker.getByLabel(t.comparePicker.left, { exact: true }).selectOption(await picker.getByLabel(t.comparePicker.right, { exact: true }).inputValue());
  await expect(picker.getByRole('button', { name: t.comparePicker.apply, exact: true })).toBeDisabled();
  await page.keyboard.press('Escape');
  await expect(pickerButton).toBeFocused();
  await expect(guide.getByRole('button', { name: t.guide.actions[5], exact: true })).toBeEnabled();
  const before = await fullProject(page, t);
  const button = guide.getByRole('button', { name: t.guide.exportProject, exact: true });
  await expect(button).toHaveAccessibleDescription(t.guide.exportProjectHint);
  await guide.getByRole('button', { name: t.guide.actions[5], exact: true }).focus();
  await page.keyboard.press('Tab');
  await expect(button).toBeFocused();
  expect(await button.evaluate(element => getComputedStyle(element).outlineStyle)).not.toBe('none');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('experiment-export.png'), fullPage: true });
  const pending = page.waitForEvent('download');
  await button.press('Enter');
  const download = await pending;
  expect(download.suggestedFilename()).toBe('ghost-rehearsal-abc.json');
  const text = await readFile((await download.path())!, 'utf8');
  const experiment = JSON.parse(text) as ProjectDocument;
  expect(experiment.plans).toHaveLength(3);
  expect(experiment.scenarios).toHaveLength(1);
  expect(experiment.plans.some(plan => original.plans.some(old => old.id === plan.id))).toBe(false);
  expect(experiment.scenarios.some(scenario => original.scenarios.some(old => old.id === scenario.id))).toBe(false);
  const all = JSON.parse(before) as ProjectDocument;
  for (const plan of experiment.plans) expect(plan).toEqual(all.plans.find(item => item.id === plan.id));
  expect(await fullProject(page, t)).toBe(before);
  await info.attach('ABC-experiment', { body: text, contentType: 'application/json' });
  await guide.getByRole('button', { name: t.guide.exit, exact: true }).click();
  await page.getByRole('tab', { name: t.modes.Build, exact: true }).click();
  await page.locator('input[type=file]').first().setInputFiles({ name: download.suggestedFilename(), mimeType: 'application/json', buffer: Buffer.from(text) });
  await expect(page.locator('.status-notice')).toHaveText(t.notices.imported);
  expect(await fullProject(page, t)).toBe(text);
  await page.getByRole('tab', { name: t.modes.Compare, exact: true }).click();
  await expect(pickerButton).toBeEnabled();
  await pickerButton.click();
  const c = experiment.plans.find(plan => !!plan.sourcePlanId)!;
  const b = experiment.plans.find(plan => plan.id === c.sourcePlanId)!;
  const left = picker.getByLabel(t.comparePicker.left, { exact: true });
  const right = picker.getByLabel(t.comparePicker.right, { exact: true });
  await left.selectOption(b.id);
  await expect(picker.getByRole('alert')).toHaveText(t.comparePicker.distinct);
  await expect(left).toHaveAccessibleDescription(t.comparePicker.distinct);
  await expect(picker.getByRole('button', { name: t.comparePicker.apply, exact: true })).toBeDisabled();
  await right.selectOption(c.id);
  await picker.getByLabel(t.run.scope, { exact: true }).selectOption('cutoff');
  await expect(picker.getByLabel(t.run.scope, { exact: true })).toHaveValue('cutoff');
  await picker.getByLabel(t.run.scope, { exact: true }).selectOption('run_to_completion');
  await expect(picker.getByRole('alert')).toHaveCount(0);
  await expect(picker.getByText(t.comparePicker.leaveGuide, { exact: true })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath('comparison-picker.png'), fullPage: true });
  const worker = page.waitForEvent('worker');
  await picker.getByRole('button', { name: t.comparePicker.apply, exact: true }).focus();
  await page.keyboard.press('Enter');
  expect((await worker).url()).toMatch(/\/assets\/worker-[^/]+\.js$/);
  await expect(picker).toHaveCount(0);
  await expect(pickerButton).toBeEnabled();
  await expect(page.locator('.comparison-identities > span')).toHaveText([`A · ${b.name}`, `B · ${c.name}`]);
  await page.locator('.report-step > summary').filter({ hasText: t.compare.steps.outcomes }).click();
  const outcome = (key: keyof Messages['compare']['rows']) => page.locator('.outcome-table').getByRole('row').filter({ has: page.getByRole('rowheader', { name: t.compare.rows[key], exact: true }) });
  await expect(outcome('completed').locator('td').nth(0)).toHaveText('41');
  await expect(outcome('completed').locator('td').nth(1)).toHaveText('72');
  await expect(outcome('unfinished').locator('td').nth(1)).toHaveText('218');
  await expect(outcome('left').locator('td').nth(1)).toHaveText('10');
  await page.locator('.comparison-options > summary').click();
  const basis = page.getByLabel(t.review.basis, { exact: true });
  await expect(basis.locator('option[value=completion]')).toBeEnabled();
  await basis.selectOption('completion');
  await expect(basis).toHaveValue('completion');
  await page.locator('.comparison-options > summary').click();
  const finalCompleted = await outcome('completed').locator('td').allTextContents();
  async function runPair(scope: 'cutoff' | 'run_to_completion') {
    await pickerButton.click();
    await picker.getByLabel(t.run.scope, { exact: true }).selectOption(scope);
    const nextWorker = page.waitForEvent('worker');
    await picker.getByRole('button', { name: t.comparePicker.apply, exact: true }).click();
    expect((await nextWorker).url()).toMatch(/\/assets\/worker-[^/]+\.js$/);
    await expect(picker).toHaveCount(0);
    await expect(pickerButton).toBeEnabled();
  }
  async function revealOutcomes() {
    const summary = page.locator('.report-step > summary').filter({ hasText: t.compare.steps.outcomes });
    if (await summary.locator('..').getAttribute('open') === null) await summary.click();
  }
  // A full run preserves the selected final basis.
  await runPair('run_to_completion');
  await page.locator('.comparison-options > summary').click();
  await expect(basis).toHaveValue('completion');
  await page.locator('.comparison-options > summary').click();
  await revealOutcomes();
  await expect(outcome('completed').locator('td')).toHaveText(finalCompleted);
  // Executing cutoff from a final view must select available cutoff statistics.
  await runPair('cutoff');
  await page.locator('.comparison-options > summary').click();
  await expect(basis).toHaveValue('cutoff');
  await expect(basis.locator('option[value=completion]')).toBeDisabled();
  await page.locator('.comparison-options > summary').click();
  await revealOutcomes();
  await expect(outcome('completed').locator('td').nth(0)).toHaveText('41');
  await expect(outcome('completed').locator('td').nth(1)).toHaveText('72');
  // Running to completion again must not discard the user's cutoff view.
  await runPair('run_to_completion');
  await page.locator('.comparison-options > summary').click();
  await expect(basis).toHaveValue('cutoff');
  await expect(basis.locator('option[value=completion]')).toBeEnabled();
  await page.locator('.comparison-options > summary').click();
  await revealOutcomes();
  await expect(outcome('completed').locator('td').nth(0)).toHaveText('41');
  await expect(outcome('completed').locator('td').nth(1)).toHaveText('72');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await fullProject(page, t)).toBe(text);
  expect(errors).toEqual([]);
});
