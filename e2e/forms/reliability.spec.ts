import { expect, test } from '@playwright/test';
import { MESSAGES } from '../../src/i18n/messages';

for (const viewport of [{ width: 390, height: 568 }, { width: 390, height: 844 }, { width: 1280, height: 720 }]) {
  test.describe(`${viewport.width}x${viewport.height}`, () => {
    test.use({ viewport });
    test.setTimeout(60_000);
    let errors: string[];
    test.beforeEach(async ({ page }, info) => {
      errors = [];
      page.on('pageerror', error => errors.push(error.message));
      page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
      await page.addInitScript(lang => localStorage.setItem('ghost-rehearsal.lang', lang), info.project.name.endsWith('zh') ? 'zh' : 'en');
      await page.goto('./');
    });
    test.afterEach(() => expect(errors).toEqual([]));

    test('invalid import stacks visually and Escape closes one layer', async ({ page }, info) => {
      const t = MESSAGES[info.project.name.endsWith('zh') ? 'zh' : 'en'];
      const picker = page.waitForEvent('filechooser');
      await page.getByRole('button', { name: t.eventSetup.import, exact: true }).click();
      await (await picker).setFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') });
      const error = page.getByRole('dialog', { name: t.stage.checksTitle });
      await expect(error).toBeVisible();
      await expect(error.getByRole('button', { name: t.common.closeDialog })).toBeFocused();
      await page.keyboard.press('Tab');
      await expect(error.getByRole('button', { name: t.common.closeDialog })).toBeFocused();
      await page.keyboard.press('Shift+Tab');
      await expect(error.getByRole('button', { name: t.common.closeDialog })).toBeFocused();
      await expect.soft(error.evaluate(element => {
        const rect = element.getBoundingClientRect();
        return element.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2));
      })).resolves.toBe(true);
      await page.screenshot({ path: info.outputPath('import-stack.png') });
      await page.keyboard.press('Escape');
      await expect.soft(page.getByRole('dialog', { name: t.eventSetup.title })).toBeVisible({ timeout: 1500 });
      await expect.soft(page.getByRole('button', { name: t.eventSetup.import, exact: true })).toBeFocused({ timeout: 1500 });
      await page.keyboard.press('Escape');
      await expect(page.getByRole('dialog')).toHaveCount(0);
    });

    test('new event accepts an empty numeric draft and keeps footer reachable', async ({ page }, info) => {
      const t = MESSAGES[info.project.name.endsWith('zh') ? 'zh' : 'en'];
      await page.getByRole('textbox', { name: t.dialogs.eventName }).fill('Forms rehearsal');
      const number = page.getByLabel(t.dialogs.count, { exact: true });
      await number.selectText();
      await number.press('Backspace');
      await expect.soft(number).toHaveValue('', { timeout: 1500 });
      const create = page.getByRole('button', { name: t.eventSetup.create, exact: true });
      await create.focus();
      const box = await create.boundingBox();
      expect.soft(box && box.y >= 0 && box.y + box.height <= viewport.height).toBe(true);
      await expect.soft(create).toBeInViewport({ ratio: 1, timeout: 1500 });
      await expect(page.getByRole('dialog').getByRole('heading', { name: t.eventSetup.title })).toBeInViewport({ ratio: 1 });
      await page.screenshot({ path: info.outputPath('event-footer.png') });
      for (const raw of ['', '-', '0', '1.5', '10001', '1e999']) {
        await number.fill(raw);
        await create.click();
        await expect(number).toHaveAttribute('aria-invalid', 'true');
        const errorId = await number.getAttribute('aria-describedby');
        expect(errorId).toBeTruthy();
        await expect(page.locator(`[id="${errorId}"]`)).toHaveText(/.+/);
        await expect(page.getByRole('dialog')).toBeVisible();
      }
      for (const raw of ['1', '10000']) {
        await number.fill(raw);
        await number.press('Enter');
        await expect(number).toHaveAttribute('aria-invalid', 'false');
        await expect(page.getByRole('dialog')).toBeVisible();
      }
      await number.fill('12');
      await number.press('Tab');
      await create.click();
      await expect(page.getByRole('dialog')).toHaveCount(0);
      await expect(page.getByLabel(t.eventSetup.active)).toContainText('Forms rehearsal');
    });

    test('resource tabs support arrow keys and panel relationships', async ({ page }, info) => {
      const t = MESSAGES[info.project.name.endsWith('zh') ? 'zh' : 'en'];
      await page.getByRole('button', { name: t.eventSetup.demo, exact: true }).click();
      await page.getByRole('tab', { name: t.modes.Build, exact: true }).click();
      await page.locator('.side-link').filter({ hasText: t.sidebar.resources }).click();
      const first = page.getByRole('tab', { name: t.dialogs.tabResources, exact: true });
      const second = page.getByRole('tab', { name: t.dialogs.tabAssignments, exact: true });
      await first.focus();
      await first.press('ArrowRight');
      await expect.soft(second).toBeFocused({ timeout: 1500 });
      await expect.soft(second).toHaveAttribute('aria-selected', 'true', { timeout: 1500 });
      await expect.soft(page.getByRole('tabpanel', { name: t.dialogs.tabAssignments, exact: true })).toBeVisible({ timeout: 1500 });
      await second.press('Home');
      await expect(first).toBeFocused();
      await first.press('ArrowLeft');
      await expect(second).toBeFocused();
      await second.press('End');
      await expect(second).toBeFocused();
      await expect(first).toHaveAttribute('tabindex', '-1');
      await expect(second).toHaveAttribute('tabindex', '0');
      await second.press('Tab');
      expect(await page.getByRole('tabpanel', { name: t.dialogs.tabAssignments, exact: true }).evaluate(element => element.contains(document.activeElement))).toBe(true);
      await second.press('Home');
      const qty = page.getByRole('tabpanel', { name: t.dialogs.tabResources, exact: true }).locator('.forms-number input').last();
      const original = await qty.inputValue();
      const originalStaff = await page.getByLabel(t.dialogs.staffName, { exact: true }).first().inputValue();
      const staffCount = await page.getByLabel(t.dialogs.staffName, { exact: true }).count();
      await qty.fill('-');
      await second.click();
      await page.getByRole('button', { name: t.dialogs.applyResources, exact: true }).click();
      await expect(first).toHaveAttribute('aria-selected', 'true');
      await expect(qty).toBeFocused();
      await expect(qty).toHaveValue('-');
      await qty.fill(original);
      await qty.press('Enter');
      await page.getByRole('button', { name: t.review.addShift, exact: true }).first().click();
      await page.getByRole('button', { name: t.review.removeShift, exact: true }).first().click();
      expect(await page.getByRole('dialog').evaluate(element => element.contains(document.activeElement))).toBe(true);
      await page.getByRole('button', { name: t.dialogs.removeStaff, exact: true }).first().click();
      expect(await page.getByRole('dialog').evaluate(element => element.contains(document.activeElement))).toBe(true);
      await page.getByRole('button', { name: t.common.cancel, exact: true }).click();
      await page.locator('.side-link').filter({ hasText: t.sidebar.resources }).click();
      await expect(page.getByLabel(t.dialogs.staffName, { exact: true })).toHaveCount(staffCount);
      await page.getByLabel(t.dialogs.staffName, { exact: true }).first().fill('Forms volunteer');
      await page.getByRole('button', { name: t.dialogs.applyResources, exact: true }).click();
      await expect(page.getByRole('dialog')).toHaveCount(0);
      await page.getByRole('button', { name: t.header.undo, exact: true }).click();
      await page.locator('.side-link').filter({ hasText: t.sidebar.resources }).click();
      await expect(page.getByLabel(t.dialogs.staffName, { exact: true }).first()).toHaveValue(originalStaff);
    });

    test('scenario minutes, cancel, removal focus and one successful Apply', async ({ page }, info) => {
      const t = MESSAGES[info.project.name.endsWith('zh') ? 'zh' : 'en'];
      await page.getByRole('button', { name: t.eventSetup.demo, exact: true }).click();
      await page.getByRole('tab', { name: t.modes.Build, exact: true }).click();
      const settings = page.getByRole('button', { name: t.eventSetup.settings, exact: true });
      await settings.click();
      const cutoff = page.getByLabel(t.dialogs.cutoff, { exact: true });
      const oldValue = await cutoff.inputValue();
      await cutoff.fill('1.5');
      await cutoff.press('Enter');
      await page.keyboard.press('Escape');
      await settings.click();
      await expect(cutoff).toHaveValue(oldValue);
      await page.getByRole('button', { name: t.review.addStream, exact: true }).click();
      await page.getByRole('button', { name: t.review.removeStream, exact: true }).last().click();
      await expect(page.getByRole('button', { name: t.review.addStream, exact: true })).toBeFocused();
      await cutoff.fill('1.5');
      await cutoff.press('Enter');
      const apply = page.getByRole('button', { name: t.dialogs.applyShared(2), exact: true });
      await apply.focus();
      await expect(apply).toBeInViewport({ ratio: 1 });
      await expect(page.getByRole('dialog').getByRole('heading', { name: t.dialogs.scenarioTitle })).toBeInViewport({ ratio: 1 });
      await page.screenshot({ path: info.outputPath('scenario-footer.png') });
      await apply.click();
      await expect(page.getByRole('dialog')).toHaveCount(0);
      await page.getByLabel(t.header.more, { exact: true }).click();
      await page.getByRole('button', { name: t.sidebar.scenarioJson, exact: true }).click();
      expect(JSON.parse(await page.getByLabel(t.dialogs.jsonLabel).inputValue()).observationCutoff).toBe(90);
      await page.keyboard.press('Escape');
      await page.getByRole('button', { name: t.header.undo, exact: true }).click();
      await settings.click();
      await expect(cutoff).toHaveValue(oldValue);
    });

    test('JSON long errors, template save and rename keep actions reachable', async ({ page }, info) => {
      const t = MESSAGES[info.project.name.endsWith('zh') ? 'zh' : 'en'];
      await page.getByRole('button', { name: t.eventSetup.demo, exact: true }).click();
      await page.getByRole('tab', { name: t.modes.Build, exact: true }).click();
      await page.getByLabel(t.header.more, { exact: true }).click();
      await page.getByRole('button', { name: t.sidebar.planJson, exact: true }).click();
      const json = page.getByLabel(t.dialogs.jsonLabel);
      const original = await json.inputValue();
      const invalid = JSON.parse(original);
      invalid['unexpected'.repeat(200)] = true;
      await json.fill(JSON.stringify(invalid));
      await page.getByRole('button', { name: t.dialogs.checkApply, exact: true }).click();
      await expect(page.getByRole('alert')).not.toBeEmpty();
      const close = page.getByRole('button', { name: t.common.close, exact: true });
      await close.focus();
      await close.press('Tab');
      await expect(page.getByRole('button', { name: t.dialogs.checkApply, exact: true })).toBeFocused();
      await expect(page.getByRole('button', { name: t.dialogs.checkApply, exact: true })).toBeInViewport({ ratio: 1 });
      await expect(close).toBeInViewport({ ratio: 1 });
      await page.screenshot({ path: info.outputPath('json-error-footer.png') });
      await json.fill(original);
      await page.getByRole('button', { name: t.dialogs.checkApply, exact: true }).click();
      await page.getByRole('button', { name: t.templates.savePlan, exact: true }).click();
      await page.getByLabel(t.templates.name, { exact: true }).fill('Forms template');
      const save = page.getByRole('dialog').locator('button[type="submit"]');
      await save.focus();
      await expect(save).toBeInViewport({ ratio: 1 });
      await save.press('Enter');
      await expect(page.getByRole('dialog')).toHaveCount(0);
      await page.getByRole('button', { name: t.review.rename, exact: true }).first().click();
      await page.getByLabel(t.review.planName, { exact: true }).fill('Forms renamed');
      await page.getByRole('dialog').getByRole('button', { name: t.header.save, exact: true }).focus();
      await expect(page.getByRole('dialog').getByRole('button', { name: t.header.save, exact: true })).toBeInViewport({ ratio: 1 });
      await page.keyboard.press('Enter');
      await expect(page.getByRole('dialog')).toHaveCount(0);
      await expect(page.locator('.plan-list')).toContainText('Forms renamed');
    });

    test('Inspector decimal drafts, external undo, entity switch and checkbox groups', async ({ page }, info) => {
      const t = MESSAGES[info.project.name.endsWith('zh') ? 'zh' : 'en'];
      await page.getByRole('button', { name: t.eventSetup.demo, exact: true }).click();
      await page.getByRole('tab', { name: t.modes.Build, exact: true }).click();
      const service = page.locator('.plan-node.type-service').first();
      await service.click();
      await page.getByRole('combobox', { name: t.inspector.distribution, exact: true }).selectOption('fixed');
      const duration = page.getByLabel(t.inspector.serviceTime, { exact: true });
      const original = await duration.inputValue();
      await duration.fill('0.5');
      await duration.press('Enter');
      await duration.fill('-');
      await page.getByRole('button', { name: t.header.undo, exact: true }).click();
      await expect(duration).toHaveValue(original);
      await page.getByRole('button', { name: t.header.redo, exact: true }).click();
      await expect(duration).toHaveValue('0.5');
      await page.locator('.plan-node.type-service').nth(1).click();
      await duration.fill('0.5');
      await duration.press('Enter');
      await service.click();
      await duration.fill('-');
      await page.locator('.plan-node.type-service').nth(1).click();
      await expect(duration).toHaveValue('0.5');
      await service.click();
      await expect(duration).toHaveValue('0.5');
      const capacity = page.getByLabel(t.inspector.maxConcurrent);
      await capacity.fill('');
      await capacity.press('Enter');
      await expect(capacity).toHaveValue('');
      await page.getByRole('button', { name: t.inspector.advanced, exact: true }).click();
      expect(JSON.parse(await page.getByLabel(t.dialogs.jsonLabel).inputValue()).maxConcurrent).toBeUndefined();
      await page.keyboard.press('Escape');
      await page.locator('.plan-node.type-decision').nth(1).click();
      const probability = page.getByLabel(t.inspector.probabilities, { exact: true }).first();
      await probability.fill('0.15');
      await probability.press('Enter');
      await page.getByRole('button', { name: t.inspector.advanced, exact: true }).click();
      expect(JSON.parse(await page.getByLabel(t.dialogs.jsonLabel).inputValue()).routing.branches[0].weight).toBe(0.15);
      await page.keyboard.press('Escape');
      await page.locator('.plan-node.type-entrance').first().click();
      const streams = page.getByRole('group', { name: t.inspector.streams, exact: true });
      const checks = streams.getByRole('checkbox');
      const before = await checks.evaluateAll(elements => elements.map(element => (element as HTMLInputElement).checked));
      await streams.locator('label').last().click();
      const after = await checks.evaluateAll(elements => elements.map(element => (element as HTMLInputElement).checked));
      expect(after.slice(0, -1)).toEqual(before.slice(0, -1));
      expect(after.at(-1)).toBe(!before.at(-1));
      await checks.last().press('Space');
      expect(await checks.evaluateAll(elements => elements.map(element => (element as HTMLInputElement).checked))).toEqual(before);
      await page.locator('.plan-node.type-subflow').first().click();
      const members = page.getByRole('group', { name: t.inspector.members, exact: true });
      await expect(members).toBeVisible();
      expect(await page.locator('label label').count()).toBe(0);
      const memberChecks = members.getByRole('checkbox');
      const membersBefore = await memberChecks.evaluateAll(elements => elements.map(element => (element as HTMLInputElement).checked));
      await members.locator('label').first().click();
      const membersAfter = await memberChecks.evaluateAll(elements => elements.map(element => (element as HTMLInputElement).checked));
      expect(membersAfter.slice(1)).toEqual(membersBefore.slice(1));
      expect(membersAfter[0]).toBe(!membersBefore[0]);
      await memberChecks.first().press('Space');
      expect(await memberChecks.evaluateAll(elements => elements.map(element => (element as HTMLInputElement).checked))).toEqual(membersBefore);
    });
  });
}
